"""Summarise demo/out/results.jsonl into demo/out/results.json and demo/out/results.md.

    /tmp/p116/venv/bin/python presentation116/demo/harness/summarize.py
"""

from __future__ import annotations

import json
import statistics as st
from collections import Counter, defaultdict
from pathlib import Path

from meter import PRICES

DEMO = Path(__file__).resolve().parent.parent
OUT = DEMO / "out"
ORDER = ["kimi-k3.1-pro", "glm-5.3", "claude-opus-5.5", "claude-fable-5-2"]
OPEN = {"kimi-k3.1-pro", "glm-5.3"}


def main() -> None:
    rows = [json.loads(l) for l in (OUT / "results.jsonl").read_text().splitlines()
            if l.strip() and json.loads(l)["model"] in ORDER]
    tasks = [t["id"] for t in json.loads((DEMO / "tasks" / "tasks.json").read_text())]
    by_model: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_model[r["model"]].append(r)

    models = {}
    for m in [m for m in ORDER if m in by_model]:
        rs = by_model[m]
        passed = [r for r in rs if r["pass"]]
        fmt = Counter(f["kind"] for r in rs for f in r["format_failures"])
        usage = {k: sum(r["usage"][k] for r in rs) for k in rs[0]["usage"]}
        usd = sum(r["usd"] for r in rs)
        per_task = {t: {"runs": sum(1 for r in rs if r["task"] == t),
                        "passed": sum(1 for r in rs if r["task"] == t and r["pass"])} for t in tasks}
        models[m] = {
            "open_weights": m in OPEN,
            "model_id": rs[0]["model_id"],
            "adapter": rs[0]["adapter"],
            "price_in": PRICES[m].input, "price_out": PRICES[m].output, "price_option": PRICES[m].option,
            "runs": len(rs),
            "passed": len(passed),
            "pass_rate": round(len(passed) / len(rs), 4),
            "tasks_solved_every_run": sum(1 for t in tasks if per_task[t]["runs"] and per_task[t]["passed"] == per_task[t]["runs"]),
            "tasks_solved_at_least_once": sum(1 for t in tasks if per_task[t]["passed"] > 0),
            "per_task": per_task,
            "stops": dict(Counter(r["stop"] for r in rs)),
            "model_calls": sum(r["calls"] for r in rs),
            "calls_median": st.median(r["calls"] for r in rs),
            "tool_calls": sum(r["tool_calls"] for r in rs),
            "format_failures": sum(fmt.values()),
            "format_failures_by_kind": dict(fmt),
            "runs_with_format_failure": sum(1 for r in rs if r["format_failures"]),
            "no_tool_turns": sum(r["no_tool_turns"] for r in rs),
            "api_errors": sum(len(r["api_errors"]) for r in rs),
            "runs_with_api_error": sum(1 for r in rs if r["api_errors"]),
            "tokens": usage,
            "reasoning_share_of_output": round(usage["reasoning"] / usage["output"], 4) if usage["output"] else 0,
            "wall_s_median": round(st.median(r["wall_s"] for r in rs), 1),
            "wall_s_total": round(sum(r["wall_s"] for r in rs), 1),
            "usd_total": round(usd, 4),
            "usd_per_run": round(usd / len(rs), 4),
            "usd_per_pass": round(usd / len(passed), 4) if passed else None,
        }

    task_view = {t: {m: models[m]["per_task"][t] for m in models} for t in tasks}
    total_usd = round(sum(v["usd_total"] for v in models.values()), 4)
    smoke = OUT.parent / "out-smoke" / "spend.jsonl"
    smoke_usd = round(sum(json.loads(l)["usd"] for l in smoke.read_text().splitlines()
                          if l.strip() and json.loads(l)["model"] in ORDER), 4) if smoke.exists() else 0.0
    summary = {"runs": len(rows), "tasks": tasks, "models": models, "per_task": task_view,
               "usd_matrix": total_usd, "usd_smoke": smoke_usd, "usd_total": round(total_usd + smoke_usd, 4),
               "first_finish": min(r["finished_at"] for r in rows), "last_finish": max(r["finished_at"] for r in rows)}
    (OUT / "results.json").write_text(json.dumps(summary, indent=2))

    lines = ["# Demo results (generated by harness/summarize.py)", "",
             f"{len(rows)} runs · {len(tasks)} tasks · matrix spend ${total_usd:.2f} at list price "
             f"(+ smoke ${smoke_usd:.2f}) · {summary['first_finish']} → {summary['last_finish']}", "",
             "| model | open | pass | rate | solved 3/3 | fmt fail | api err | calls med | wall med s | tokens in | tokens out | reasoning % | $ total | $/pass |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for m, v in models.items():
        lines.append(f"| {m} | {'yes' if v['open_weights'] else 'no'} | {v['passed']}/{v['runs']} | {v['pass_rate']:.0%} | "
                     f"{v['tasks_solved_every_run']}/{len(tasks)} | {v['format_failures']} | {v['api_errors']} | {v['calls_median']} | "
                     f"{v['wall_s_median']} | {v['tokens']['input']:,} | {v['tokens']['output']:,} | "
                     f"{v['reasoning_share_of_output']:.0%} | {v['usd_total']:.2f} | "
                     f"{'' if v['usd_per_pass'] is None else format(v['usd_per_pass'], '.3f')} |")
    lines += ["", "Per task (passed/runs):", "", "| task | " + " | ".join(models) + " |", "|---|" + "---|" * len(models)]
    for t in tasks:
        lines.append(f"| {t} | " + " | ".join(f"{task_view[t][m]['passed']}/{task_view[t][m]['runs']}" for m in models) + " |")
    lines += ["", "Stops and format failures:", ""]
    for m, v in models.items():
        lines.append(f"- {m}: stops {v['stops']}; format failures {v['format_failures_by_kind'] or 0}; "
                     f"no-tool turns {v['no_tool_turns']}")
    (OUT / "results.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
